#!/usr/bin/env node

/**
 * geo-registry.mjs
 *
 * The single source of truth for country → region resolution.
 *
 * Everything is keyed on ISO 3166-1 alpha-2. Before this module the codebase
 * carried TWO independent maps keyed on messy display names — COUNTRY_TO_ISO in
 * geocoder.mjs (for coordinates) and COUNTRY_CONTINENT in shared-constants.mjs
 * (for continents) — which had to be kept in sync by hand and could silently
 * disagree. Keying on ISO2 makes that class of drift impossible: a country has
 * exactly one code, one canonical name, and one region.
 *
 * Region assignments for every country that was already mapped are carried over
 * unchanged from COUNTRY_CONTINENT, so this is not a re-guess of existing data.
 *
 * MARITIME and SPACE are first-class regions, not fallbacks. A sighting over the
 * Philippine Sea or from the ISS genuinely has no country; recording that as a
 * fact is honest, whereas defaulting it to AMERICAS (the previous behaviour) was
 * not. Nothing here ever guesses — resolution tiers live in geo-resolve.mjs.
 *
 * Coverage against the live corpus is enforced by `yarn geo:audit`.
 */

