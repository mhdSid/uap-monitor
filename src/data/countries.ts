// ─── Lookup helpers ─────────────────────────────────────────────────

/** Case-insensitive index built on first access */
let _lcContinentMap: Map<string, Continent> | null = null
let _lcCoordsMap: Map<string, { lat: number; lng: number }> | null = null

function lcContinentMap(): Map<string, Continent> {
  if (!_lcContinentMap) {
    _lcContinentMap = new Map()
    for (const [k, v] of Object.entries(COUNTRY_CONTINENT)) {
      _lcContinentMap.set(k.toLowerCase(), v)
    }
  }
  return _lcContinentMap
}

function lcCoordsMap(): Map<string, { lat: number; lng: number }> {
  if (!_lcCoordsMap) {
    _lcCoordsMap = new Map()
    for (const [k, v] of Object.entries(COUNTRY_COORDS)) {
      _lcCoordsMap.set(k.toLowerCase(), v)
    }
  }
  return _lcCoordsMap
}

/**
 * Resolve a country name to its continent.
 * Case-insensitive. Returns fallback if not found.
 */
export function resolveContinent(country: string, fallback = Continent.AMERICAS): Continent {
  if (!country) return fallback
  return COUNTRY_CONTINENT[country] ?? lcContinentMap().get(country.toLowerCase()) ?? fallback
}

/**
 * Resolve a country name to its default coordinates.
 * Case-insensitive. Returns null if not found.
 */
export function resolveCoords(country: string): { lat: number; lng: number } | null {
  if (!country) return null
  return COUNTRY_COORDS[country] ?? lcCoordsMap().get(country.toLowerCase()) ?? null
}
